#!/usr/bin/env python3
"""
Run Python implementation on R-generated test data.

This script loads the test data generated by R and runs the Python
implementation to produce comparable results.

Usage:
    python3 validation/run_python_implementation.py
"""

import sys
import os
import numpy as np
import pandas as pd
from scipy import sparse
from pathlib import Path
import pickle

# Add parent directory to path
sys.path.insert(0, str(Path(__file__).parent.parent))

from ldpred2_python import ldpred2_inf, ldpred2_grid, ldpred2_auto


def load_test_data(data_dir):
    """Load test data generated by R."""
    print("Loading test data...")
    
    # Load summary statistics
    df_beta = pd.read_csv(data_dir / "df_beta.csv")
    print(f"  - Summary statistics: {len(df_beta)} variants")
    
    # Load LD matrix
    corr_dense = np.load(data_dir / "corr_matrix.npy")
    # Convert to sparse
    corr = sparse.csr_matrix(corr_dense)
    print(f"  - LD matrix: {corr.shape}")
    print(f"  - Sparsity: {100 * (1 - corr.nnz / (corr.shape[0] * corr.shape[1])):.2f}%")
    
    return df_beta, corr


def run_ldpred2_inf(corr, df_beta, output_dir):
    """Run LDpred2-inf."""
    print("\n" + "="*70)
    print("Running LDpred2-inf (Python)")
    print("="*70)
    
    beta_inf = ldpred2_inf(corr, df_beta, h2=0.5)
    
    print(f"  - Number of estimates: {len(beta_inf)}")
    print(f"  - Range: [{beta_inf.min():.6f}, {beta_inf.max():.6f}]")
    print(f"  - Non-zero: {np.sum(beta_inf != 0)}")
    
    # Save results
    np.save(output_dir / "beta_inf_py.npy", beta_inf)
    print("  ✓ Results saved")
    
    return beta_inf


def run_ldpred2_grid(corr, df_beta, output_dir):
    """Run LDpred2-grid."""
    print("\n" + "="*70)
    print("Running LDpred2-grid (Python)")
    print("="*70)
    
    # Define parameter grid (same as R)
    params = [
        {'p': 0.01, 'h2': 0.3, 'sparse': False},
        {'p': 0.01, 'h2': 0.3, 'sparse': True},
        {'p': 0.01, 'h2': 0.5, 'sparse': False},
        {'p': 0.01, 'h2': 0.5, 'sparse': True},
        {'p': 0.1, 'h2': 0.3, 'sparse': False},
        {'p': 0.1, 'h2': 0.3, 'sparse': True},
        {'p': 0.1, 'h2': 0.5, 'sparse': False},
        {'p': 0.1, 'h2': 0.5, 'sparse': True},
    ]
    
    print(f"  - Testing {len(params)} parameter combinations")
    print(f"  - Burn-in: 50, Iterations: 100")
    
    beta_grid = ldpred2_grid(
        corr, df_beta, params,
        burn_in=50,
        num_iter=100,
        seed=42
    )
    
    print(f"  - Result dimensions: {beta_grid.shape}")
    
    # Check for divergence
    for i in range(beta_grid.shape[1]):
        if np.any(np.isnan(beta_grid[:, i])):
            print(f"  ⚠ WARNING: Parameter set {i+1} diverged (contains NaN)")
    
    # Save results
    np.save(output_dir / "beta_grid_py.npy", beta_grid)
    
    # Save parameters
    params_df = pd.DataFrame(params)
    params_df.to_csv(output_dir / "params_grid_py.csv", index=False)
    
    print("  ✓ Results saved")
    
    return beta_grid


def run_ldpred2_auto(corr, df_beta, output_dir):
    """Run LDpred2-auto."""
    print("\n" + "="*70)
    print("Running LDpred2-auto (Python)")
    print("="*70)
    
    print("  - Initial h²: 0.5")
    print("  - Initial p: [0.01, 0.1]")
    print("  - Burn-in: 500, Iterations: 200")
    print("  - Shrinkage: 0.95")
    
    auto_result = ldpred2_auto(
        corr, df_beta,
        h2_init=0.5,
        vec_p_init=[0.01, 0.1],
        burn_in=500,
        num_iter=200,
        allow_jump_sign=False,
        shrink_corr=0.95,
        seed=42
    )
    
    print(f"  - Number of chains: {len(auto_result)}")
    
    # Print results for each chain
    for i, result in enumerate(auto_result):
        print(f"\n  Chain {i+1}:")
        print(f"    h² estimate: {result['h2_est']:.6f}")
        print(f"    p estimate: {result['p_est']:.6f}")
        print(f"    α estimate: {result['alpha_est']:.6f}")
        
        # Check for divergence
        if np.any(np.isnan(result['beta_est'])):
            print(f"    ⚠ WARNING: Chain diverged (contains NaN)")
    
    # Save results
    with open(output_dir / "auto_py.pkl", "wb") as f:
        pickle.dump(auto_result, f)
    
    print("\n  ✓ Results saved")
    
    return auto_result


def main():
    print("="*70)
    print("Running Python Implementation on R Test Data")
    print("="*70)
    print()
    
    # Setup paths
    data_dir = Path("validation/r_results")
    output_dir = Path("validation/py_results")
    output_dir.mkdir(exist_ok=True, parents=True)
    
    # Check if R data exists
    if not data_dir.exists():
        print("ERROR: R test data not found!")
        print(f"Expected directory: {data_dir}")
        print("\nPlease run the R script first:")
        print("  Rscript validation/generate_r_reference.R")
        return 1
    
    # Load test data
    try:
        df_beta, corr = load_test_data(data_dir)
    except Exception as e:
        print(f"ERROR loading test data: {e}")
        return 1
    
    # Run each method
    try:
        beta_inf = run_ldpred2_inf(corr, df_beta, output_dir)
    except Exception as e:
        print(f"ERROR in LDpred2-inf: {e}")
        import traceback
        traceback.print_exc()
    
    try:
        beta_grid = run_ldpred2_grid(corr, df_beta, output_dir)
    except Exception as e:
        print(f"ERROR in LDpred2-grid: {e}")
        import traceback
        traceback.print_exc()
    
    try:
        auto_result = run_ldpred2_auto(corr, df_beta, output_dir)
    except Exception as e:
        print(f"ERROR in LDpred2-auto: {e}")
        import traceback
        traceback.print_exc()
    
    # Summary
    print("\n" + "="*70)
    print("Python Implementation Complete")
    print("="*70)
    print()
    print(f"Results saved to: {output_dir}")
    print()
    print("Next step:")
    print("  python3 validation/compare_with_r.py \\")
    print("    --r-dir validation/r_results \\")
    print("    --py-dir validation/py_results")
    print()
    print("="*70)
    
    return 0


if __name__ == "__main__":
    sys.exit(main())

